<p>Email <a href="mailto:{{ config('sas.enquiry_email') }}">{{ config('sas.enquiry_email') }}</a> with your name, the service and your enquiry or case reference, and say what went wrong. We reply within 5 working days. Approved refunds are paid back to the original payment method within 14 days, less any third-party costs described above. Bank or payment-provider processing times may add to this.</p>

