<h2>1. Before you pay</h2>
<p>Online payment is not available on this site yet. Before any paid work begins we send you a written scope that states what we will do, the deliverables, the timeline, the fee, how many revisions are included and how the fee is paid. You are only charged once you have accepted that scope. If anything in the written scope differs from this page, the written scope for your service applies to that service.</p>

<h2>2. Cancelling a service</h2>
<ul>
    <li><strong>Before work starts:</strong> you may cancel and we will refund the full amount you paid.</li>
    <li><strong>After work has started:</strong> you may cancel at any time. We refund the part of the fee for work not yet done. Work already delivered, and time already spent on it, is charged in proportion to the written scope.</li>
    <li><strong>Consultations:</strong> if you cancel or ask to reschedule at least 24 hours before the booked time, the fee (if any) is refunded or moved to a new time. Within 24 hours, or if you do not attend, the fee is not refunded unless we cancel or are at fault.</li>
</ul>

<h2>3. What is not refundable</h2>
<ul>
    <li><strong>Outcomes.</strong> We do not guarantee scholarship selection, admission, attestation acceptance or a visa decision, so a rejection or delay by a funder, university, embassy or authority is not a reason for a refund.</li>
    <li><strong>Third-party costs</strong> once paid or committed to someone else (application, test, translation, courier, attestation or visa fees). We pass on any refund the third party gives us.</li>
    <li><strong>Work delivered as agreed</strong> and accepted, or that you did not use.</li>
</ul>

<h2>4. When we will refund in full or in part</h2>
<ul>
    <li>We cancel the service or cannot deliver it, for reasons not caused by you.</li>
    <li>We fail to deliver a core deliverable in the written scope and do not fix it within a reasonable time after you tell us.</li>
    <li>You were charged by mistake or twice.</li>
</ul>

